package BeforeDSA.ConditionalThinking.Level1;

// Check if a number is divisible by 5.
public class Q3 {
    public static void main(String[] args) {
        int num = 15;
        if (num % 5 == 0) {
            System.out.println("Divisible  by 5");
        } else {
            System.out.println("Not divisible by 5");
        }
    }
}
