package BeforeDSA.ConditionalThinking.Level1;

// Check if a number is even or odd
public class Q2 {
    public static void main(String[] args) {
        int num = 12;
        if (num % 2 == 0) {
            System.out.println("Even");
        } else {
            System.out.println("Odd");
        }
    }
}
