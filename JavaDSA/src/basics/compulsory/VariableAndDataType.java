package basics.compulsory;

public class VariableAndDataType {
    public static void main(String[] args) {
        //* primitives
        //* Integers
        byte b = 12;
        short s = 105;
        int i = 3259;
        long l = 25462L;

        //* Floating Points
        float f = 1.25f;
        double d = 589.2358844;

        //* char
        char c = 'S';

        //* boolean
        boolean bool = true;
    }
}
